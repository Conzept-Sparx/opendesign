import path from "path";
import { BLOCK_END, BLOCK_START, CMD_PREFIX, SPEC_DIR, TOOL, TOOL_TITLE, Tool, VERSION } from "./constants";
import { PKG_ROOT, asString, frontmatter, listFiles, read, write } from "./fsx";

export interface Workflow { id: string; title: string; description: string; body: string }

const ORDER = ["next", "explore", "lock", "view", "change", "artefact", "system", "brief", "research", "users", "journeys", "requirements", "ideate", "structure", "screen", "generate", "critique", "verify", "rationale"];

export function loadWorkflows(): Workflow[] {
  const files = listFiles(path.join(PKG_ROOT, "workflows"), (f) => f.endsWith(".md"));
  const wfs = files.map((f) => {
    const { data, body } = frontmatter(read(f));
    return { id: asString(data.id), title: asString(data.title), description: asString(data.description), body: body.trim() };
  });
  return wfs.sort((a, b) => ORDER.indexOf(a.id) - ORDER.indexOf(b.id));
}

const PREAMBLE = `Before starting, read \`${SPEC_DIR}/CONVENTIONS.md\` and \`${SPEC_DIR}/config.json\`. If the \`${SPEC_DIR}/\` folder doesn't exist, ask the designer to run \`${TOOL} init\` first.`;
const FOOTER = `<!-- Generated by ${TOOL} ${VERSION}. Run \`${TOOL} update\` to refresh; local edits will be overwritten. -->`;

function skill(wf: Workflow) {
  return `---\nname: ${TOOL}-${wf.id}\ndescription: ${wf.description}\n---\n\n# ${TOOL_TITLE}: ${wf.title}\n\n${PREAMBLE}\n\n${wf.body}\n\n${FOOTER}\n`;
}

function command(wf: Workflow) {
  return `---\ndescription: ${TOOL_TITLE} — ${wf.title}\nargument-hint: [what to work on]\n---\n\n# ${TOOL_TITLE}: ${wf.title}\n\n${PREAMBLE}\n\n${wf.body}\n\nDesigner input: $ARGUMENTS\n\n${FOOTER}\n`;
}

export function invocation(tool: Tool, id: string) {
  if (tool === "claude") return `/${CMD_PREFIX}:${id}`;
  if (tool === "opencode") return `/${CMD_PREFIX}-${id}`;
  return `$${TOOL}-${id}`;
}

/** Writes skills (all tools) and slash commands (Claude Code, OpenCode). Returns written paths. */
export function writeAgentFiles(root: string, tools: Tool[], wfs: Workflow[]): string[] {
  const written: string[] = [];
  const put = (rel: string, content: string) => { write(path.join(root, rel), content); written.push(rel); };
  for (const wf of wfs) {
    if (tools.includes("claude")) {
      put(`.claude/skills/${TOOL}-${wf.id}/SKILL.md`, skill(wf));
      put(`.claude/commands/${CMD_PREFIX}/${wf.id}.md`, command(wf));
    }
    if (tools.includes("codex")) put(`.codex/skills/${TOOL}-${wf.id}/SKILL.md`, skill(wf));
    if (tools.includes("opencode")) {
      put(`.opencode/skills/${TOOL}-${wf.id}/SKILL.md`, skill(wf));
      put(`.opencode/commands/${CMD_PREFIX}-${wf.id}.md`, command(wf));
    }
  }
  return written;
}

function block(tool: Tool, wfs: Workflow[]) {
  const rows = wfs.map((wf) => `| \`${invocation(tool, wf.id)}\` | ${wf.title} |`).join("\n");
  return `${BLOCK_START}
## ${TOOL_TITLE} (spec-driven UX)

This project keeps its UX spec in \`${SPEC_DIR}/\`. Before any design, UX, prototype or UI work,
read \`${SPEC_DIR}/CONVENTIONS.md\` and follow it. The spec is the source of truth; the prototype is
generated from it and every element that satisfies a requirement carries \`data-req="REQ-…"\`.
Run \`${TOOL} verify\` after changing specs or prototype code.

| Command | Workflow |
|---|---|
${rows}
${BLOCK_END}`;
}

/** Insert or replace the managed block in AGENTS.md / CLAUDE.md. */
export function writeInstructionBlocks(root: string, tools: Tool[], wfs: Workflow[]): string[] {
  const targets: [string, Tool][] = [];
  if (tools.includes("claude")) targets.push(["CLAUDE.md", "claude"]);
  if (tools.includes("codex")) targets.push(["AGENTS.md", "codex"]);
  else if (tools.includes("opencode")) targets.push(["AGENTS.md", "opencode"]);
  const written: string[] = [];
  for (const [file, tool] of targets) {
    const p = path.join(root, file);
    let text = read(p);
    let content = block(tool, wfs);
    if (file === "AGENTS.md" && tools.includes("codex") && tools.includes("opencode")) {
      content = content.replace(/\| Command \| Workflow \|[\s\S]*?(?=\n<!-- OPENDESIGN:END)/,
        `| Codex | OpenCode | Workflow |\n|---|---|---|\n` +
        wfs.map((wf) => `| \`${invocation("codex", wf.id)}\` | \`${invocation("opencode", wf.id)}\` | ${wf.title} |`).join("\n"));
    }
    const re = new RegExp(`${BLOCK_START}[\\s\\S]*?${BLOCK_END}`);
    text = re.test(text) ? text.replace(re, content) : (text.trim() ? `${text.trimEnd()}\n\n${content}\n` : `${content}\n`);
    write(p, text);
    written.push(file);
  }
  return written;
}
